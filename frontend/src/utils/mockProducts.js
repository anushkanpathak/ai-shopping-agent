// Smart product search on mock data
export function searchMockProducts({ keywords = [], category = null, budget = null, count = 6 }) {
  const query = [...keywords, category].filter(Boolean).join(' ').toLowerCase();

  let results = MOCK_PRODUCTS.filter(p => {
    const searchable = `${p.title} ${p.vendor} ${p.type} ${p.tags.join(' ')} ${p.description}`.toLowerCase();

    if (query) {
      const words = query.split(/\s+/).filter(w => w.length > 2);
      return words.some(w => searchable.includes(w));
    }
    return true;
  });

  // Filter by budget
  if (budget) {
    results = results.filter(p => parseFloat(p.price) <= budget);
  }

  // If no matches, return trending products
  if (results.length === 0) {
    results = MOCK_PRODUCTS.slice(0, count);
  }

  return results.slice(0, count);
}
